import test from 'node:test';
import assert from 'node:assert/strict';
import {createApi} from '../src/api.js';
import {Gateway} from '../src/gateway.js';
import {createAuth} from '../src/auth.js';
import {once} from 'node:events';
const credentials=['admin','viewer','reviewer','agent'].map((role,i)=>({role,identity:role==='agent'?'a':role,token:String(i).repeat(32)}));
const policy={version:'1',rules:[{id:'read',agent:'a',tool:'read',effect:'approval',arguments:{id:{type:'string'}}}]};
test('credential validation and invalid tokens',()=>{assert.throws(()=>createAuth([{token:'short',role:'admin',identity:'a'}]));const auth=createAuth(credentials);assert.equal(auth('Bearer '+credentials[0].token).role,'admin');assert.equal(auth('Bearer '+'x'.repeat(32)),null);});
test('HTTP roles, identity binding, origin, review, audit, metrics and controls',async t=>{
  const gateway=new Gateway({policy,tools:{read:async a=>a.id}});
  const server=createApi({gateway,credentials});server.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>new Promise(r=>server.close(r)));
  const base='http://127.0.0.1:'+server.address().port;
  const call=async(path,role,body,extra={})=>{const token=credentials.find(x=>x.role===role)?.token;const response=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{...(token?{Authorization:'Bearer '+token}:{}),...(body===undefined?{}:{'Content-Type':'application/json'}),...extra},...(body===undefined?{}:{body:JSON.stringify(body)})});return {status:response.status,body:response.headers.get('content-type').includes('json')?await response.json():await response.text()};};
  assert.equal((await call('/health')).status,401);
  assert.equal((await call('/health','agent')).status,200);
  assert.equal((await call('/v1/status','agent')).status,403);
  assert.equal((await call('/v1/status','viewer',undefined,{Origin:'https://example.test'})).status,403);
  assert.equal((await call('/v1/invoke','admin',{tool:'read',args:{id:'x'}})).status,403);
  assert.equal((await call('/v1/invoke','agent',{agent:'b',tool:'read',args:{id:'x'}})).status,400);
  assert.equal((await call('/v1/preview','agent',{tool:'read',args:{id:'x'}})).body.decision,'approval');
  const req=(await call('/v1/invoke','agent',{tool:'read',args:{id:'x'}})).body;
  assert.equal((await call('/v1/approvals','viewer')).status,403);
  assert.equal((await call('/v1/approvals','reviewer')).body.length,1);
  assert.equal((await call('/v1/review','admin',{approvalId:req.approvalId,approve:true})).status,403);
  assert.equal((await call('/v1/review','reviewer',{approvalId:req.approvalId,approve:true})).body.result,'x');
  assert.equal((await call('/v1/audit/export','viewer')).body.verified,true);
  assert.equal((await call('/v1/audit?decision=allow','viewer')).body.total,1);
  assert.match((await call('/metrics','viewer')).body,/agentguard_events_total/);
  assert.equal((await call('/v1/halt','viewer',{halted:true})).status,403);
  assert.equal((await call('/v1/halt','admin',{halted:true})).status,200);
  assert.equal((await call('/v1/invoke','agent',{tool:'read',args:{id:'x'}})).body.decision,'deny');
  assert.equal((await call('/v1/policy','admin',{policy,expectedRevision:1})).body.revision,2);
  assert.equal((await call('/v1/history','viewer')).body.length,1);
  assert.equal((await call('/v1/rollback','admin',{revision:1,expectedRevision:2})).body.revision,3);
  assert.equal((await call('/v1/disable','admin',{agent:'a',disabled:true})).status,200);
  assert.equal((await call('/v1/alerts','viewer')).status,200);
});
